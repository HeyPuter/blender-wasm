#!/usr/bin/env python3
"""Generate no-op stubs for symbols Blender's wasm link leaves undefined.

Static linking tolerates these via -sERROR_ON_UNDEFINED_SYMBOLS=0 because none
are reachable: they are CPython's bz2/sqlite3 modules (no backing library in the
sysroot), the fork's two WebGPU entry points (called even with the backend off),
and WasmFS backends only used by the browser build. Nothing in `--background`
touches any of them.

Dynamic linking is stricter. Under -sMAIN_MODULE the loader resolves undefined
symbols at module load: with ASSERTIONS=1 it aborts outright, and with
ASSERTIONS=0 the glue trips over its own stub bookkeeping
("Cannot read properties of undefined (reading 'value')"). Either way the module
never starts, so the symbols have to genuinely exist.

Defining them as no-ops is safe precisely because they are unreachable — if one
were ever called it would return zero rather than crash, which is the same
outcome the static build had.

Usage: gen_undef_stubs.py <undefined-symbols.txt> <out.c>

The list is scripts/undef_symbols.txt (tracked); `#` lines are comments.
"""
import sys

# execinfo.h, imported by numpy's side module. Blender's crash handler is the
# only caller; returning "no frames" is the same outcome the static build had.
SIGNATURES = {
    "backtrace": "int backtrace(void **buffer, int size)"
                 " { (void)buffer; (void)size; return 0; }",
    "backtrace_symbols": "char **backtrace_symbols(void *const *buffer, int size)"
                         " { (void)buffer; (void)size; return 0; }",
    "backtrace_symbols_fd": "void backtrace_symbols_fd(void *const *buffer, int size, int fd)"
                            " { (void)buffer; (void)size; (void)fd; }",
}


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2

    with open(sys.argv[1], encoding="utf8") as handle:
        symbols = sorted({line.strip() for line in handle
                          if line.strip() and not line.lstrip().startswith("#")})

    lines = [
        "/* Generated by scripts/gen_undef_stubs.py — do not edit. */",
        "/* No-op definitions for unreachable symbols; see the generator docstring. */",
        "",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "",
    ]

    # A zero-returning long is assignment-compatible with every use site here,
    # and wasm-ld only needs *a* definition to stop treating the symbol as
    # undefined. Declared with no prototype so any call signature links.
    #
    # EXCEPT when a SIDE_MODULE imports the symbol. Static linking only needs a
    # definition to exist, but `WebAssembly.Instance` type-checks every import
    # at instantiation: numpy's _multiarray_umath imports `backtrace`, and a
    # `() -> i32` stub against its real `(i32, i32) -> i32` fails the whole
    # module with "imported function does not match the expected type", which
    # surfaces as `ImportError: Error importing numpy`. Symbols reachable from
    # a side module therefore need their true prototype.
    for symbol in symbols:
        lines.append(SIGNATURES.get(symbol, f"long {symbol}(void) {{ return 0; }}"))

    lines += ["", "#ifdef __cplusplus", "}", "#endif", ""]

    with open(sys.argv[2], "w", encoding="utf8") as handle:
        handle.write("\n".join(lines))

    print(f"generated {len(symbols)} stub(s) -> {sys.argv[2]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
