#!/usr/bin/env node
// Build the package: embed protocol.py as a TS string, compile, copy assets,
// and take the runtime from ./build.sh browser into runtime/.
//   node scripts/build.mjs                    full build into dist/ (+ runtime/ when built)
//   node scripts/build.mjs --generate-only    just src/project/protocol.generated.ts
//   node scripts/build.mjs --require-runtime  fail without a runtime (prepack)
// BLENDER_WEB_RUNTIME_DIR overrides where the runtime comes from.
import { spawnSync } from "node:child_process";
import { chmodSync, copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const protocol = readFileSync(join(root, "src/project/protocol.py"), "utf8");
writeFileSync(join(root, "src/project/protocol.generated.ts"),
  "// Generated by scripts/build.mjs from protocol.py; do not edit.\n"
  + `export const PROTOCOL_SOURCE: string = ${JSON.stringify(protocol)};\n`);
if (process.argv.includes("--generate-only")) process.exit(0);

rmSync(join(root, "dist"), { recursive: true, force: true });
const tsc = spawnSync(process.execPath, [join(root, "node_modules/typescript/bin/tsc"), "-p", join(root, "tsconfig.json")], { stdio: "inherit" });
if (tsc.status !== 0) process.exit(tsc.status ?? 1);
// Plain-JS assets that run as-is: classic workers (they importScripts the
// emscripten glue) and Node's one-shot runner (a CommonJS child process).
for (const file of ["project/protocol.py", "browser/session-worker.js", "browser/run-worker.js", "node/run-once.cjs"]) {
  mkdirSync(dirname(join(root, "dist", file)), { recursive: true });
  copyFileSync(join(root, "src", file), join(root, "dist", file));
}
chmodSync(join(root, "dist/runtime/cli.js"), 0o755);
console.log("built dist/");

// The runtime, per flavour: the glue, the brotli-compressed module and data,
// and the manifest with every file's sha256 (compressed and raw).
//   mt  ./build.sh browser     (pthreads, cross-origin isolated pages)
//   st  ./build.sh browser-st  (single-threaded with JSPI, any page)
const SOURCES = {
  mt: process.env.BLENDER_WEB_RUNTIME_MT ?? resolve(root, "../../dist/blender-wasm-browser"),
  st: process.env.BLENDER_WEB_RUNTIME_ST ?? resolve(root, "../../dist/blender-wasm-browser-st"),
};
const RUNTIME_FILES = ["blender.js", "blender.wasm.br", "blender.data.br", "manifest.json"];
rmSync(join(root, "runtime"), { recursive: true, force: true });
const missing = [];
for (const [flavor, source] of Object.entries(SOURCES)) {
  if (!RUNTIME_FILES.every((name) => existsSync(join(source, name)))) {
    missing.push(`${flavor} (${source})`);
    continue;
  }
  const out = join(root, "runtime", flavor);
  mkdirSync(out, { recursive: true });
  for (const name of RUNTIME_FILES) copyFileSync(join(source, name), join(out, name));
  const manifest = JSON.parse(readFileSync(join(out, "manifest.json"), "utf8"));
  console.log(`runtime ${flavor}: ${manifest.forkRevision} from ${source}`);
}
// runtime/ is a servable layout as it is (a CDN serves it from the package):
// the workers, and a root manifest naming the flavours and how their binaries
// are encoded (the page decodes them itself when no server does).
const flavors = {};
for (const flavor of Object.keys(SOURCES)) {
  const path = join(root, "runtime", flavor, "manifest.json");
  if (existsSync(path)) flavors[flavor] = JSON.parse(readFileSync(path, "utf8"));
}
if (Object.keys(flavors).length) {
  for (const name of ["session-worker.js", "run-worker.js"]) copyFileSync(join(root, "src/browser", name), join(root, "runtime", name));
  // The page's brotli decoder (scripts/build_brotli_decoder.sh), for a CDN that serves the .br files as they are.
  const decoder = process.env.BLENDER_WEB_BROTLI_DECODER ?? resolve(root, "../../dist/brotli-decode.wasm");
  if (existsSync(decoder)) copyFileSync(decoder, join(root, "runtime/brotli-decode.wasm"));
  else if (process.argv.includes("--require-runtime")) {
    console.error(`no ${decoder}: run scripts/build_brotli_decoder.sh`);
    process.exit(1);
  }
  writeFileSync(join(root, "runtime/manifest.json"), JSON.stringify({
    forkRevision: Object.values(flavors)[0].forkRevision,
    encoding: "br",
    flavors,
  }, null, 2));
}
if (missing.length) {
  if (process.argv.includes("--require-runtime")) {
    console.error(`missing runtime flavours: ${missing.join(", ")}; run ./build.sh browser and ./build.sh browser-st`);
    process.exit(1);
  }
  console.log(`built without runtime flavours: ${missing.join(", ")}`);
}
